def search_departments_by_keywords(query_text):
    """Find relevant departments based on keywords in the query"""
    query_lower = query_text.lower()
    relevant_departments = []
    
    for dept_name, dept_info in DEPARTMENT_KNOWLEDGE_BASE.items():
        relevance_score = 0
        
        # Check keywords
        for keyword in dept_info.get("keywords", []):
            if keyword.lower() in query_lower:
                relevance_score += 2
        
        # Check responsibilities
        for responsibility in dept_info.get("responsibilities", []):
            if any(word in query_lower for word in responsibility.lower().split()):
                relevance_score += 1
        
        # Check example grievances
        for example in dept_info.get("example_grievances", []):
            if any(word in query_lower for word in example.lower().split() if len(word) > 3):
                relevance_score += 1
        
        if relevance_score > 0:
            relevant_departments.append((dept_name, relevance_score, dept_info))
    
    # Sort by relevance score
    relevant_departments.sort(key=lambda x: x[1], reverse=True)
    return relevant_departments